# 사이트의 랜딩 페이지 (app.py LANDINGS)
def page(ja):
    if "荷物" in ja or "スーツケース" in ja or "手ぶら" in ja:
        return "/ (짐 배송 배너) · 새 랜딩 후보"
    if "仁川空港" in ja and ("送迎" in ja or "タクシー" in ja):
        return "/incheon-airport-sougei"
    if any(w in ja for w in ("チャーター", "貸切", "観光タクシー", "ハイヤー", "レンタカー")):
        return "/seoul-charter"
    if "送迎" in ja:
        return "/seoul-sougei"
    return "/"


rows, seen = [], set()


def add(ja, ko, kind, place, svc, pri, note=""):
    ja, ko = " ".join(ja.split()), " ".join(ko.split())
    if ja in seen:
        return
    seen.add(ja)
    rows.append([ja, ko, kind, place, svc, pri, page(ja) if kind != "정보형" else "블로그 글 후보", note])


