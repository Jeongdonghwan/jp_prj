def ko(ja):
    out, miss = [], []
    for t in ja.split():
        k = WORDS.get(t) or WORDS.get(t.lower())
        if k is None:
            miss.append(t)
            k = t
        out.append(k)
    s = " ".join(out).replace(" 에서", "에서").replace(" 까지", "까지").replace(" 로 ", "로 ")
    return s, miss


