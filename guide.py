def faq_for(p, c, n=5):
    import re
    text = " ".join(p["kws"])
    skip = COVERED.get(p["intent"], ()) if p["place"] else ()
    out = []
    for pat, q, a in _faqs(c):
        if any(pat.startswith(k) for k in skip):
            continue
        if re.search(pat, text) and a:
            out.append((q, a))
    return (out + DEFAULT_FAQ)[:max(4, min(n, len(out)))]


