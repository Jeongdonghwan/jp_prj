def _near(a, b):
    return math.hypot(DIST[a]["lat"] - DIST[b]["lat"], DIST[a]["lng"] - DIST[b]["lng"])


def _km(a, b):  # 위경도 직선거리(km), 한 자리
    la = math.radians((DIST[a]["lat"] + DIST[b]["lat"]) / 2)
    return round(math.hypot((DIST[a]["lat"] - DIST[b]["lat"]) * 111, (DIST[a]["lng"] - DIST[b]["lng"]) * 111 * math.cos(la)), 1)


def related(p, today=None, n=8):
    opn = [q for q in open_pages(today) if q["id"] != p["id"]]
    pl, ap = p["place"], p["airport"]

    def rank(q):
        same_pl = bool(pl) and q["place"] == pl
        same_ap = q["airport"] == ap
        near = _near(pl, q["place"]) if pl and q["place"] else 9
        return (not same_pl, not (same_ap and q["intent"] == p["intent"]), near, -q["score"])
    return sorted(opn, key=rank)[:n]


