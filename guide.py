def timing(c, P, dep):
    """도착: 착륙 시각별 호텔 도착 예상 / 출발: 출발 시각별 픽업 시각 (주행시간에서 계산)."""
    if not c["legs"]:
        return None
    mn = c["legs"][0][2]
    rows = []
    for h in ((8, 11, 14, 18, 21) if dep else (9, 13, 17, 21, 23)):
        if dep:
            rows.append((f"{h}時発の便", f"{_pickup(mn, h)}ごろ{P}を出発"))
        else:
            t = h * 60 + 50 + math.ceil(mn * (1.4 if 7 <= h <= 19 else 1.1) / 10) * 10  # 입국·짐 찾기 50분 + 주행
            rows.append((f"{h}時着の便", f"{t // 60 % 24}時{t % 60:02d}分ごろ{P}のホテル着"))
    return rows


